"""Builds gui/00_tmm_situation_hiding.gui: hides the trait map situation from the
situation list and the HUD banners, so it only shows up through the map mode button.

Copies two vanilla GUI types verbatim and changes one line in each (marked TMM):
- vbox_situation_group_foldout (gui/window_situation_list.gui): hides the situation
  group types tagged tmm_hidden (common/situation/situation_group_types).
- button_situation_banner (gui/hud.gui): hides the banner of the situation whose
  phase is tmm_watch (same test as vanilla's natural disaster highlight).
GUI types are registered by the first file that declares them; gui/00_* loads first.
Re-run after each CK3 patch.
"""
import os

GAME = r"G:/SteamLibrary/steamapps/common/Crusader Kings III/game"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gui", "00_tmm_situation_hiding.gui")


def extract(rel, name):
    raw = open(os.path.join(GAME, rel), "rb").read().decode("utf-8-sig")
    lines = raw.replace("\r\n", "\n").split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith(f"\ttype {name} "))
    end = next(i for i in range(start + 1, len(lines)) if lines[i] == "\t}")
    return lines[start:end + 1]


# Situation list: one group foldout per situation group type
fold = extract("gui/window_situation_list.gui", "vbox_situation_group_foldout")
i = next(i for i, l in enumerate(fold) if l.startswith('\t\tvisible = "[') and l.endswith(']"'))
inner = fold[i][len('\t\tvisible = "['):-len(']"')]
fold[i:i + 1] = [
    "\t\t# TMM - hide the trait map situation group",
    f"\t\tvisible = \"[And( Not( SituationGroupType.HasTag( 'tmm_hidden' ) ), {inner} )]\"",
]

# HUD: one banner per visible situation
banner = extract("gui/hud.gui", "button_situation_banner")
j = next(i for i, l in enumerate(banner) if l.strip() == 'name = "situation_banner_item"')
banner[j + 1:j + 1] = [
    "\t\t# TMM - no banner for the trait map situation",
    "\t\tvisible = \"[Not( EqualTo_string( Situation.GetTopCurrentPhase.GetType.GetKey, 'tmm_watch' ) )]\"",
]

header = [
    "# Trait Map Mode - overrides of two vanilla GUI types (vanilla 1.20.0.4),",
    "# generated by tools/build_situation_hiding.py. Only the lines after the 'TMM' comments differ.",
    "",
    "types TmmSituationHiding",
    "{",
]
out = header + fold + [""] + banner + ["}"]
with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(out))
print("foldout line", i, "banner line", j, "->", OUT)
